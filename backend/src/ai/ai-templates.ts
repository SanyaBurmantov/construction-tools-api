function normalise(text: string) {
  return fixHomoglyphs(text).toLowerCase().replace(/ё/g, 'е');
}

/**
 * The product kind as the name states it: its first one or two words, after
 * any leading size («10х100х160 мм бур…») and before the first preposition —
 * «Клещи для хомутов» is pliers, «Сверло для перфоратора» is a bit.
 */
export function nameHead(name: string) {
  const words = normalise(name)
    .replace(/[«»"'()[\],;:]/g, ' ')
    .split(/\s+/)
    .filter(Boolean);
  while (words.length && /\d|^(мм|см|м|шт|х|x)\.?$/.test(words[0]))
    words.shift();
  const head: string[] = [];
  for (const word of words) {
    if (PREPOSITIONS.has(word) || head.length === 2) break;
    head.push(word);
  }
  return head.join(' ');
}

/**
 * The template for one product: by the head of its name, then its own
 * category, then the whole category chain — the first subject a non-generic
 * template matches decides.
 */
export function productTemplate(params: {
  categoryPath: string;
  name: string;
}): AiTemplate {
  return explainTemplate(params).template;
}

/** Which subject decided the kind — what the admin «объяснить» shows. */
export type TemplateChoice = {
  template: AiTemplate;
  by: 'name' | 'category' | 'chain' | 'default';
  subject: string;
};

export function explainTemplate(params: {
  categoryPath: string;
  name: string;
}): TemplateChoice {
  const chain = params.categoryPath.split(' / ').filter(Boolean);
  const subjects: Array<[TemplateChoice['by'], string]> = [
    ['name', nameHead(params.name)],
    ['category', normalise(chain[chain.length - 1] ?? '')],
    ['chain', normalise(params.categoryPath)],
  ];
  for (const [by, subject] of subjects) {
    if (!subject) continue;
    const found = PRODUCT_TEMPLATES.find(
      (template) => template !== GENERIC && template.match.test(subject),
    );
    if (found) return { template: found, by, subject };
  }
  return { template: GENERIC, by: 'default', subject: '' };
}

/**
 * The word stems a kind is recognised by, readable: the regex without its
 * syntax. Shown in the admin so «why did this anchor get the fastener guide»
 * has an answer on screen.
 */
export function templateKeywords(template: AiTemplate): string[] {
  if (template === GENERIC) return [];
  const words = template.match.source
    .replace(/\(\?<?[!=][^)]*\)/g, '')
    .split('|')
    .map((part) =>
      part
        .replace(/\\w\*|\\s\*|\\s\+|\\w\+/g, ' ')
        .replace(/\[\^?[^\]]*\]\??/g, (cls) => (cls.includes('а-я') ? '' : ''))
        .replace(/[()?*+^$\\.]/g, '')
        .replace(/\s+/g, ' ')
        .trim(),
    )
    .filter((word) => word.length > 2);
  return [...new Set(words)];
}

